#!/usr/bin/env python3
"""Builds the iOS Localizable.strings (es, en) from the web console's dictionaries plus ios-strings.json,
so the iPad and web apps use the same wording. Run after changing either: python3 ios/scripts/gen_strings.py"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PAIR = re.compile(r'^\s*"([^"]+)":\s*"((?:[^"\\]|\\.)*)",?\s*$')


def web(language: str) -> dict:
    entries = {}
    for line in (ROOT / "web/src/i18n" / f"{language}.ts").read_text(encoding="utf-8").splitlines():
        match = PAIR.match(line)
        if match:
            entries[match.group(1)] = json.loads(f'"{match.group(2)}"')
    return entries


def escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main() -> None:
    extra = json.loads((ROOT / "ios/SparkleWash/Resources/ios-strings.json").read_text(encoding="utf-8"))
    for language in ("es", "en"):
        strings = web(language)
        strings.update({key: value[language] for key, value in extra.items()})
        out = ROOT / "ios/SparkleWash/Resources" / f"{language}.lproj" / "Localizable.strings"
        out.parent.mkdir(parents=True, exist_ok=True)
        lines = ["/* Generated by ios/scripts/gen_strings.py from web/src/i18n and ios-strings.json. Do not edit. */", ""]
        lines += [f'"{escape(key)}" = "{escape(value)}";' for key, value in sorted(strings.items())]
        out.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{out.relative_to(ROOT)}: {len(strings)} strings")


if __name__ == "__main__":
    main()
